// Copies compiled ABIs from ../contracts/out into src/abi as typed TS constants.
// Run after `forge build`:  npm run abi
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const out = join(root, "..", "contracts", "out");
const dest = join(root, "src", "abi");
mkdirSync(dest, { recursive: true });

const contracts = [
  ["SwissRWAPlatform.sol/SwissRWAPlatform.json", "platformAbi"],
  ["AssetRegistry.sol/AssetRegistry.json", "assetRegistryAbi"],
  ["Token.sol/Token.json", "tokenAbi"],
  ["IdentityRegistry.sol/IdentityRegistry.json", "identityRegistryAbi"],
  ["IdentityRegistryStorage.sol/IdentityRegistryStorage.json", "identityStorageAbi"],
  ["Identity.sol/Identity.json", "identityAbi"],
  ["MaxHoldersModule.sol/MaxHoldersModule.json", "maxHoldersAbi"],
  ["LockUpModule.sol/LockUpModule.json", "lockUpAbi"],
  ["SupplyLimitModule.sol/SupplyLimitModule.json", "supplyLimitAbi"],
  ["CountryRestrictModule.sol/CountryRestrictModule.json", "countryRestrictAbi"],
  ["ClaimIssuer.sol/ClaimIssuer.json", "claimIssuerAbi"],
];

for (const [file, name] of contracts) {
  const { abi } = JSON.parse(readFileSync(join(out, file), "utf8"));
  writeFileSync(
    join(dest, `${name}.ts`),
    `// Auto-generated by scripts/export-abi.mjs — do not edit.\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
  console.log(`wrote src/abi/${name}.ts`);
}

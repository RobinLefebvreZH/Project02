export const countryName = (code: number) => COUNTRIES.find((c) => c.code === code)?.name ?? `Country ${code}`;

/** "US, GB" → numeric ISO codes; unknown entries are reported. */
export function parseCountries(input: string) {
  const codes: number[] = [];
  const unknown: string[] = [];
  for (const raw of input.split(/[\s,;]+/).filter(Boolean)) {
    const v = raw.toUpperCase();
    const c = COUNTRIES.find((x) => x.iso2 === v || String(x.code) === v);
    if (c) codes.push(c.code);
    else unknown.push(raw);
  }
  return { codes, unknown };
}

